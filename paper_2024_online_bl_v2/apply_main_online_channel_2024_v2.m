function [received, clean, diagnostics] = ...
        apply_main_online_channel_2024_v2(frame, chanParams, params, n0)
%APPLY_MAIN_ONLINE_CHANNEL_2024_V2 Send an explicit-CP augmented frame through the main physical channel.
    local_validate_inputs(frame, chanParams, params, n0);
    cp_frame = frame.cp_frame;
    block_length = params.M + params.cp_length_2024;
    total_columns = params.total_columns_2024;
    serial_length = block_length * total_columns;
    transmitted = reshape(cp_frame, serial_length, params.Nt);
    fsamp = params.M * params.df;
    reference_duration = params.doppler_reference_columns_2024 * ...
        block_length / fsamp;

    path_count = numel(chanParams.pathDelays);
    maximum_delay = max(chanParams.pathDelays);
    path_signals = complex(zeros(serial_length + maximum_delay, path_count));
    for path_index = 1:path_count
        path = struct( ...
            'pathGains', chanParams.pathGains(path_index), ...
            'pathDelays', chanParams.pathDelays(path_index), ...
            'pathDopplerFreqs', ...
                chanParams.pathDopplers(path_index) / reference_duration);
        for tx = 1:params.Nt
            steering = exp(-1j*2*pi*(tx-1)*params.ddlt * ...
                sind(chanParams.AoDs(path_index)));
            path_signal = steering * dopplerChannel(transmitted(:, tx), fsamp, path);
            path_rows = 1:numel(path_signal);
            path_signals(path_rows, path_index) = ...
                path_signals(path_rows, path_index) + path_signal;
        end
    end

    receive_steering = exp(1j*2*pi*(0:params.Nr-1).' * params.ddlr * ...
        sind(chanParams.AoAs(:).'));
    serial_clean_full = (receive_steering * path_signals.').';
    serial_clean = serial_clean_full(1:serial_length, :);
    padded_clean = reshape(serial_clean, block_length, total_columns, params.Nr);
    clean = strip_column_cp_2024_v2(padded_clean, params);
    if n0 == 0
        received = clean;
    else
        received = clean + sqrt(n0/2) * ...
            (randn(size(clean)) + 1j*randn(size(clean)));
    end
    diagnostics = struct( ...
        'serial_clean_full', serial_clean_full, ...
        'serial_clean', serial_clean, ...
        'padded_clean', padded_clean, ...
        'fsamp', fsamp, ...
        'reference_duration', reference_duration);
end

function local_validate_inputs(frame, chanParams, params, n0)
    required_params = {'M','N','Nt','Nr','df','ddlt','ddlr', ...
        'cp_length_2024','total_columns_2024', ...
        'doppler_reference_columns_2024'};
    for index = 1:numel(required_params)
        if ~isfield(params, required_params{index})
            error('apply_main_online_channel_2024_v2:MissingParameter', ...
                'params.%s is required.', required_params{index});
        end
    end
    if ~isstruct(frame) || ~isfield(frame, 'cp_frame') || ...
            size(frame.cp_frame, 1) ~= params.M+params.cp_length_2024 || ...
            size(frame.cp_frame, 2) ~= params.total_columns_2024 || ...
            size(frame.cp_frame, 3) ~= params.Nt || ...
            any(~isfinite(frame.cp_frame(:)))
        error('apply_main_online_channel_2024_v2:InvalidFrame', ...
            'frame.cp_frame has invalid dimensions or values.');
    end
    required_channel = {'pathGains','pathDelays','pathDopplers','AoDs','AoAs'};
    for index = 1:numel(required_channel)
        if ~isfield(chanParams, required_channel{index})
            error('apply_main_online_channel_2024_v2:MissingChannelParameter', ...
                'chanParams.%s is required.', required_channel{index});
        end
    end
    count = numel(chanParams.pathDelays);
    for index = 1:numel(required_channel)
        values = chanParams.(required_channel{index});
        if numel(values) ~= count || any(~isfinite(values(:)))
            error('apply_main_online_channel_2024_v2:InvalidChannel', ...
                'All channel arrays must be finite and have equal length.');
        end
    end
    if any(chanParams.pathDelays(:) < 0) || ...
            any(chanParams.pathDelays(:) ~= round(chanParams.pathDelays(:))) || ...
            max(chanParams.pathDelays) > params.cp_length_2024
        error('apply_main_online_channel_2024_v2:InvalidDelay', ...
            'Integer path delays must be covered by cp_length_2024.');
    end
    if ~isscalar(n0) || ~isreal(n0) || ~isfinite(n0) || n0 < 0
        error('apply_main_online_channel_2024_v2:InvalidNoiseVariance', ...
            'n0 must be a finite nonnegative scalar.');
    end
end

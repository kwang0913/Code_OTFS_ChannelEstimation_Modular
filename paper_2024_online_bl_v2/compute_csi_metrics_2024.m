function metrics = compute_csi_metrics_2024(truth,estimate,support,lambda,threshold)
%COMPUTE_CSI_METRICS_2024 Diagnostic-only relative-lambda support metrics.
% A group is detected when lambda >= threshold*max(lambda), with lambda > 0.
    if ~isequal(size(truth),size(estimate)) || any(~isfinite(truth(:))) || ...
            any(~isfinite(estimate(:))) || numel(support) ~= numel(lambda) || ...
            any(~isfinite(lambda(:))) || any(lambda(:) < 0) || ...
            ~isscalar(threshold) || ~isfinite(threshold) || threshold < 0 || threshold > 1
        error('compute_csi_metrics_2024:InvalidInput','Invalid coefficient/support metrics inputs.');
    end
    active = lambda(:) > 0 & lambda(:) >= threshold*max(lambda(:));
    support = logical(support(:));
    hits = nnz(active & support);
    precision = hits/max(nnz(active),1); recall = hits/max(nnz(support),1);
    metrics = struct('precision',precision,'recall',recall, ...
        'f1',2*precision*recall/max(precision+recall,eps), ...
        'support_count',nnz(active),'coefficient_NMSE', ...
        norm(estimate-truth,'fro')^2/max(norm(truth,'fro')^2,eps));
end
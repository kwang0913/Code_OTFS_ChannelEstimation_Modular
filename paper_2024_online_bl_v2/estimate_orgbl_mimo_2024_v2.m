function [Hhat, state] = estimate_orgbl_mimo_2024_v2( ...
        Rpilots, PsiPilots, initial, params)
%ESTIMATE_ORGBL_MIMO_2024_V2 Sequential Bayesian updates for later pilots.
    [pilot_count, coefficient_count, receiver_count, noise_covariances] = ...
        local_validate(Rpilots, PsiPilots, initial, params);
    Hhat = initial.Hhat;
    prior_diagonal = initial.prior_diagonal(:);
    reduction_factor = initial.covariance_factor;
    converged = true(pilot_count, 1);
    innovation_norm = zeros(pilot_count, 1);
    innovation_logdet = zeros(pilot_count, 1);
    gain_norm = zeros(pilot_count, 1);

    for pilot = 2:pilot_count
        Psi = PsiPilots{pilot};
        R = Rpilots{pilot};
        Rw = noise_covariances{pilot};
        prior_times_dictionary = prior_diagonal.*Psi';
        if ~isempty(reduction_factor)
            prior_times_dictionary = prior_times_dictionary - ...
                reduction_factor*(reduction_factor'*Psi');
        end
        output_covariance = Psi*prior_times_dictionary + Rw;
        output_covariance = (output_covariance+output_covariance')/2;
        [factor, status] = chol(output_covariance, 'lower');
        if status ~= 0
            error('estimate_orgbl_mimo_2024_v2:InnovationNotPD', ...
                'Pilot %d innovation covariance is not positive definite.', pilot);
        end
        innovation = R-Psi*Hhat;
        gain = (factor'\(factor\prior_times_dictionary'))';
        Hhat = Hhat+gain*innovation;
        update_factor = prior_times_dictionary/factor';
        reduction_factor = [reduction_factor, update_factor]; %#ok<AGROW>
        innovation_norm(pilot) = norm(innovation, 'fro');
        innovation_logdet(pilot) = 2*sum(log(real(diag(factor))));
        gain_norm(pilot) = norm(gain, 'fro');
        converged(pilot) = all(isfinite(Hhat(:))) && ...
            all(isfinite(reduction_factor(:)));
        if ~converged(pilot)
            error('estimate_orgbl_mimo_2024_v2:NonFiniteState', ...
                'Pilot %d produced a non-finite posterior.', pilot);
        end
    end

    covariance_diagonal = max(real(prior_diagonal - ...
        sum(abs(reduction_factor).^2, 2)), 0);
    state = struct('lambda', initial.lambda, ...
        'prior_diagonal', prior_diagonal, ...
        'covariance_diagonal', covariance_diagonal, ...
        'covariance_factor', reduction_factor, ...
        'converged', converged, ...
        'innovation_norm', innovation_norm, ...
        'innovation_logdet', innovation_logdet, ...
        'gain_norm', gain_norm, ...
        'coefficient_count', coefficient_count, ...
        'receiver_count', receiver_count);
end

function [pilot_count, coefficient_count, receiver_count, noise_covariances] = ...
        local_validate(Rpilots, PsiPilots, initial, params)
    if ~iscell(Rpilots) || ~iscell(PsiPilots) || isempty(Rpilots) || ...
            numel(Rpilots) ~= numel(PsiPilots)
        error('estimate_orgbl_mimo_2024_v2:InvalidPilots', ...
            'Rpilots and PsiPilots must be equally sized nonempty cells.');
    end
    required_state = {'Hhat','lambda','prior_diagonal','covariance_factor'};
    if ~isstruct(initial) || ~isscalar(initial) || ...
            ~all(isfield(initial, required_state))
        error('estimate_orgbl_mimo_2024_v2:InvalidInitialState', ...
            'initial is missing posterior fields.');
    end
    if ~isstruct(params) || ~isscalar(params) || ...
            ~isfield(params, 'RwPilots') || ~iscell(params.RwPilots) || ...
            numel(params.RwPilots) ~= numel(Rpilots)
        error('estimate_orgbl_mimo_2024_v2:InvalidParams', ...
            'params.RwPilots must provide one covariance per pilot.');
    end
    pilot_count = numel(Rpilots);
    coefficient_count = size(PsiPilots{1}, 2);
    receiver_count = size(Rpilots{1}, 2);
    if ~isequal(size(initial.Hhat), [coefficient_count, receiver_count]) || ...
            numel(initial.prior_diagonal) ~= coefficient_count || ...
            size(initial.covariance_factor, 1) ~= coefficient_count || ...
            any(~isfinite(initial.Hhat(:))) || ...
            any(~isfinite(initial.prior_diagonal(:))) || ...
            any(initial.prior_diagonal(:) <= 0) || ...
            any(~isfinite(initial.covariance_factor(:)))
        error('estimate_orgbl_mimo_2024_v2:InvalidInitialState', ...
            'initial posterior dimensions or values are invalid.');
    end
    noise_covariances = params.RwPilots;
    for pilot = 1:pilot_count
        R = Rpilots{pilot};
        Psi = PsiPilots{pilot};
        Rw = noise_covariances{pilot};
        measurement_count = size(R, 1);
        if ~isnumeric(R) || ~ismatrix(R) || ...
                size(R, 2) ~= receiver_count || any(~isfinite(R(:))) || ...
                ~isnumeric(Psi) || ...
                ~isequal(size(Psi), [measurement_count, coefficient_count]) || ...
                any(~isfinite(Psi(:))) || ~isnumeric(Rw) || ...
                ~isequal(size(Rw), [measurement_count, measurement_count]) || ...
                any(~isfinite(Rw(:))) || ...
                norm(Rw-Rw', 'fro') > 100*eps(max(1, norm(Rw, 'fro')))
            error('estimate_orgbl_mimo_2024_v2:InvalidPilots', ...
                'Pilot %d has incompatible or non-finite data.', pilot);
        end
        [~, status] = chol((Rw+Rw')/2, 'lower');
        if status ~= 0
            error('estimate_orgbl_mimo_2024_v2:InvalidNoise', ...
                'Pilot %d noise covariance must be positive definite.', pilot);
        end
    end
end
function trial = simulate_trial_2024_v2(params, SNR_db, trial_idx)
%SIMULATE_TRIAL_2024_V2 Run one main-physical online RGBL/ORGBL trial.
    local_validate_inputs(params, SNR_db, trial_idx);
    rng(trial_idx);
    total_timer = tic;
    n0 = params.data_power_2024 * 10^(-SNR_db/10);
    [chanParams, ~] = generate_channel_params(params);
    if strcmpi(params.paper_gain_mode, 'unity')
        chanParams.pathGains = ones(size(chanParams.pathGains));
    end
    truth = generate_main_grid_truth_2024_v2(params, chanParams);
    frame = generate_online_pilot_frame_2024_v2(params);
    [received, ~] = apply_main_online_channel_2024_v2( ...
        frame, chanParams, params, n0);

    pilot_count = params.N_pilots_2024;
    Rpilots = cell(pilot_count, 1);
    PsiPilots = cell(pilot_count, 1);
    RwPilots = cell(pilot_count, 1);
    noise_covariance = max(n0, params.variance_floor_2024)*eye(params.M);
    for pilot = 1:pilot_count
        slot = frame.pilot_locations(pilot);
        Rpilots{pilot} = reshape(received(:, slot, :), params.M, params.Nr);
        PsiPilots{pilot} = build_main_online_dictionary_2024_v2( ...
            frame.pilots(:, :, pilot), slot, params);
        RwPilots{pilot} = noise_covariance;
    end

    timer = tic;
    [Hfirst, first_state] = estimate_rgbl_initial_2024_v2( ...
        Rpilots{1}, PsiPilots{1}, RwPilots{1}, params);
    rgbl_runtime_seconds = toc(timer);
    online_params = params;
    online_params.RwPilots = RwPilots;
    timer = tic;
    [Hhat, final_state] = estimate_orgbl_mimo_2024_v2( ...
        Rpilots, PsiPilots, first_state, online_params);
    orgbl_runtime_seconds = toc(timer);

    NMSE_RGBL = compute_main_nmse_2024_v2( ...
        chanParams, Hfirst, params, frame.data_locations);
    NMSE_ORGBL = compute_main_nmse_2024_v2( ...
        chanParams, Hhat, params, frame.data_locations);
    coefficient_NMSE_RGBL = norm(Hfirst-truth.H, 'fro')^2 / ...
        max(norm(truth.H, 'fro')^2, eps);
    coefficient_NMSE_ORGBL = norm(Hhat-truth.H, 'fro')^2 / ...
        max(norm(truth.H, 'fro')^2, eps);
    support_RGBL = compute_csi_metrics_2024( ...
        truth.H, Hfirst, truth.support, first_state.lambda, ...
        local_support_threshold(params));

    if params.trials == 1
        timer = tic;
        [bits_hat, ~, detection] = detect_lmmse_2024_v2( ...
            received, Hhat, frame, params, n0);
        detection_runtime_seconds = toc(timer);
        BER_ORGBL = mean(bits_hat(:) ~= frame.source_bits(:));
        detection_skipped = false;
    else
        BER_ORGBL = NaN;
        detection = struct('iterations', [], 'relative_residual', [], ...
            'converged', []);
        detection_runtime_seconds = 0;
        detection_skipped = true;
    end
    [true_parameters, estimated_parameters] = local_parameter_summary( ...
        chanParams, truth, Hhat, first_state.lambda, params);
    trial = struct( ...
        'NMSE_RGBL', NMSE_RGBL, ...
        'NMSE_ORGBL', NMSE_ORGBL, ...
        'coefficient_NMSE_RGBL', coefficient_NMSE_RGBL, ...
        'coefficient_NMSE_ORGBL', coefficient_NMSE_ORGBL, ...
        'BER_ORGBL', BER_ORGBL, ...
        'support_RGBL', support_RGBL, ...
        'pilot_count', pilot_count, ...
        'H_RGBL', Hfirst, ...
        'H_ORGBL', Hhat, ...
        'lambda_RGBL', first_state.lambda, ...
        'delay_grid', params.delay_grid_2024, ...
        'doppler_grid', params.doppler_grid_2024, ...
        'rgbl_iterations', first_state.iterations, ...
        'rgbl_converged', first_state.converged, ...
        'orgbl_converged', final_state.converged, ...
        'orgbl_innovation_norm', final_state.innovation_norm, ...
        'orgbl_innovation_logdet', final_state.innovation_logdet, ...
        'orgbl_gain_norm', final_state.gain_norm, ...
        'detection_iterations', detection.iterations, ...
        'detection_relative_residual', detection.relative_residual, ...
        'detection_converged', detection.converged, ...
        'detection_skipped', detection_skipped, ...
        'n0', n0, ...
        'rgbl_runtime_seconds', rgbl_runtime_seconds, ...
        'orgbl_runtime_seconds', orgbl_runtime_seconds, ...
        'detection_runtime_seconds', detection_runtime_seconds, ...
        'runtime_seconds', toc(total_timer), ...
        'true_parameters', true_parameters, ...
        'estimated_parameters', estimated_parameters);
end

function [true_parameters, estimated_parameters] = ...
        local_parameter_summary(chanParams, truth, Hhat, lambda, params)
    true_parameters = struct( ...
        'pathDelays', chanParams.pathDelays(:).', ...
        'pathDopplers', chanParams.pathDopplers(:).', ...
        'pathGridDelays', truth.pathGridDelays(:).', ...
        'pathGridDopplers', truth.pathGridDopplers(:).', ...
        'pathAtomIndices', truth.pathAtomIndices(:).', ...
        'AoAs', chanParams.AoAs(:).', ...
        'AoDs', chanParams.AoDs(:).', ...
        'pathGains', chanParams.pathGains(:).');
    Q = params.M_tau*params.G_nu;
    coefficient_norm = zeros(Q, 1);
    for atom = 1:Q
        rows = atom+(0:params.Nt-1)*Q;
        coefficient_norm(atom) = norm(Hhat(rows, :), 'fro');
    end
    [~, ranked] = sort(coefficient_norm, 'descend');
    count = min(numel(chanParams.pathDelays), Q);
    atom_indices = ranked(1:count);
    delay_indices = mod(atom_indices-1, params.M_tau)+1;
    doppler_indices = floor((atom_indices-1)/params.M_tau)+1;
    estimated_parameters = struct( ...
        'atom_indices', atom_indices, ...
        'pathDelays', params.delay_grid_2024(delay_indices), ...
        'pathDopplers', params.doppler_grid_2024(doppler_indices), ...
        'lambda', lambda(atom_indices), ...
        'coefficient_norm', coefficient_norm(atom_indices));
end

function threshold = local_support_threshold(params)
    threshold = 0.1;
    if isfield(params, 'support_threshold_2024')
        threshold = params.support_threshold_2024;
    end
end

function local_validate_inputs(params, SNR_db, trial_idx)
    required = {'M','N','Nt','Nr','M_tau','G_nu','N_pilots_2024', ...
        'variance_floor_2024','delay_grid_2024','doppler_grid_2024', ...
        'cp_length_2024','total_columns_2024', ...
        'doppler_reference_columns_2024'};
    if ~isstruct(params) || ~isscalar(params) || ~all(isfield(params, required))
        error('simulate_trial_2024_v2:InvalidParams', ...
            'params must provide the v2 main-physical configuration.');
    end
    if ~isscalar(SNR_db) || ~isreal(SNR_db) || ~isfinite(SNR_db)
        error('simulate_trial_2024_v2:InvalidSNR', ...
            'SNR_db must be finite and real.');
    end
    if ~isscalar(trial_idx) || ~isreal(trial_idx) || ...
            ~isfinite(trial_idx) || trial_idx < 0 || trial_idx ~= round(trial_idx)
        error('simulate_trial_2024_v2:InvalidTrialIndex', ...
            'trial_idx must be a nonnegative integer.');
    end
end

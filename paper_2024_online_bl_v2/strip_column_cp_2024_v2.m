function payload = strip_column_cp_2024_v2(padded, params)
%STRIP_COLUMN_CP_2024_V2 Remove the explicit cyclic prefix from every column.
    rows = params.M + params.cp_length_2024;
    if ~isnumeric(padded) || ndims(padded) > 3 || ...
            size(padded, 1) ~= rows || ...
            size(padded, 2) ~= params.total_columns_2024 || ...
            any(~isfinite(padded(:)))
        error('strip_column_cp_2024_v2:InvalidFrame', ...
            'padded must be finite (M+CP)-by-(N+Np)-by-links.');
    end
    payload = padded(params.cp_length_2024+1:end, :, :);
end
